export type Cam = {s: number; ox: number; oy: number; dx: number; dy: number};

export const cam = (t: number): Cam => {
	let i = 0;
	while (i < K.length - 2 && t >= K[i + 1][0]) i++;
	const [t0, s0, x0, y0, a0 = 0, b0 = 0] = K[i];
	const [t1, s1, x1, y1, a1 = 0, b1 = 0] = K[i + 1];
	const e = t1 > t0 ? sine((t - t0) / (t1 - t0)) : 1;
	// 硬静音那 1.3 秒镜头的漂移也冻住，之后接着走（不跳）
	const tt = t < 188.95 ? t : t < 190.25 ? 188.95 : t - 1.3;
	return {
		s: s0 + (s1 - s0) * e,
		ox: x0 + (x1 - x0) * e,
		oy: y0 + (y1 - y0) * e,
		dx: a0 + (a1 - a0) * e + 2.4 * Math.sin(tt * 0.19) + 1.4 * Math.sin(tt * 0.11 + 1.3),
		dy: b0 + (b1 - b0) * e + 1.8 * Math.sin(tt * 0.15 + 2.1),
	};
};

/** 世界坐标 → 屏幕坐标 */
export const toScreen = (c: Cam, x: number, y: number): [number, number] => [c.ox + c.dx + c.s * (x - c.ox), c.oy + c.dy + c.s * (y - c.oy)];
