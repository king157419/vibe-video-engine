import re
lines = """你一定猜到了下一个字。
所以它出现的时候，几乎没有带来任何新东西。
这一次，你猜不到。而猜不到的，才是信息。
我心里想了一个数，在1到1024之间。
你只能问“是”或“否”的问题。最少要问几次？
每问一次，就砍掉一半的可能。
512、256、128……
十个“是或否”，就是十个比特。
1948年，贝尔实验室的香农，第一次给信息找到了单位：比特。
烽火为什么值得点？因为敌人很少来。
越罕见的消息越让人惊讶，带来的信息也越多。
“广州明天不下雪”——约等于0比特。
“广州明天下雪”——将近10比特，足够登上新闻头条。
香农把这份惊奇写成公式；平均的惊奇，叫作“熵”。
所以，信息的单位，其实就是惊奇。
可我们说的话，大部分都在意料之中。
研表究明，汉字的序顺并不定一能影阅响读。
你读懂了，因为你猜得到。猜得到的部分，叫作冗余。
压缩文件，就是删掉那些猜得到的部分。
可在嘈杂的地铁里，正是冗余让你听清了广播。
冗余不是浪费，它是意义穿过噪声时的铠甲。
噪声越来越大，会不会吞没一切？
香农证明：只要不超过信道容量，错误就能少到任意小。
旅行者1号远在光要走将近一整天的地方，发射功率只有二十瓦左右，
地球依然能从噪声里，把它的每个比特认出来。
1964年，同样在贝尔实验室，两位工程师被一段噪声困住了。
他们清理了天线里的鸽子粪，噪声还在。
那是宇宙诞生之初留下的余晖。人们想删掉的噪声，竟是最大的惊奇。
但香农也特意提醒：意义，不在他的公式里。
同样多的比特，可以是一首诗，也可以是一团乱码。
乱码也让你意外，却什么都没告诉你。好的惊奇，是意外，又懂得。
当推荐流只给你意料之中的东西，它就再也告诉不了你什么。
今天你看到的东西里，有多少是你没有料到的？
一件事最值得听的时候，是你真的不知道答案的时候。
所以，去找那些你猜不到的——
一本读不懂的书，一个和你想得不一样的人，一条没走过的路。
惊奇，是世界正在告诉你新东西的声音。
这一次，由你来填。""".split("\n")
han = sum(len(re.findall(r'[\u4e00-\u9fff]', l)) for l in lines)
alnum = sum(len(re.findall(r'[0-9A-Za-z]', l)) for l in lines)
punct_free = sum(len(re.findall(r'[\u4e00-\u9fff0-9A-Za-z]', l)) for l in lines)
