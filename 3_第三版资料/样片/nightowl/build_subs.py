def min_dur(zh: str) -> float:
    return len(zh) / 4.0 + 1.2


def ceil05(x: float) -> float:
    return math.ceil(x * 20 - 1e-9) / 20.0


def build():
    out, rows = [], []
    prev_t1 = None
    for i, (sec, zh, gap, extra, fixed) in enumerate(SUBS):
        assert len(zh) <= 18, f"第 {i + 1} 句超过 18 字：{zh}（{len(zh)}）"
        assert not zh.endswith("。"), zh
        t0 = fixed if fixed is not None else round(prev_t1 + gap, 2)
        dur = ceil05(min_dur(zh)) + extra
        if i == 2:  # 押注：字幕从 10.0 停到 14.5（方案 §4.5）
            dur = 4.5
        t1 = round(t0 + dur, 2)
        if prev_t1 is not None:
            g = round(t0 - prev_t1, 3)
            hi = 2.2 if i == 17 else 1.0  # #18 前是“B = 缝”的让位（审片第二轮 P1-1），其余句间 0.4–1.0 秒
            assert 0.4 - 1e-9 <= g <= hi + 1e-9, f"第 {i + 1} 句前空隙 {g}"
        assert t1 - t0 >= min_dur(zh) - 1e-9, f"第 {i + 1} 句停留不足"
        out.append({"t0": t0, "t1": t1, "zh": zh})
        rows.append((i + 1, sec, t0, t1, zh, len(zh), min_dur(zh)))
        prev_t1 = t1
    return out, rows


def pchip(xs: list[float], ys: list[float]):
    """和 video-engine/src/v3/nightowl/data.ts 的 pchip 一模一样（Fritsch–Carlson，两端速度为 0）。"""
    n = len(xs)
    h = [xs[k + 1] - xs[k] for k in range(n - 1)]
    d = [(ys[k + 1] - ys[k]) / h[k] for k in range(n - 1)]
    m = [0.0] * n
    for k in range(1, n - 1):
        if d[k - 1] * d[k] <= 0:
            m[k] = 0.0
        else:
            w1 = 2 * h[k] + h[k - 1]
            w2 = h[k] + 2 * h[k - 1]
            m[k] = (w1 + w2) / (w1 / d[k - 1] + w2 / d[k])

    def f(x: float) -> float:
        if x <= xs[0]:
            return ys[0]
        if x >= xs[-1]:
            return ys[-1]
        k = 0
        while k < n - 2 and x > xs[k + 1]:
            k += 1
        s_ = (x - xs[k]) / h[k]
        return ((2 * s_ ** 3 - 3 * s_ ** 2 + 1) * ys[k] + (s_ ** 3 - 2 * s_ ** 2 + s_) * h[k] * m[k]
                + (-2 * s_ ** 3 + 3 * s_ ** 2) * ys[k + 1] + (s_ ** 3 - s_ ** 2) * h[k] * m[k + 1])

    return f


def mmss(t: float) -> str:
    return f"{int(t // 60)}:{t % 60:04.1f}"


